static size_t hx(uint8_t *out, const char *h)
{
	size_t n = 0;
	for (; h[0] && h[1]; h += 2) {
		unsigned v;
		sscanf(h, "%2x", &v);
		out[n++] = (uint8_t)v;
	}
	return n;
}

static int same(const uint8_t *a, size_t an, const char *hex)
{
	uint8_t b[4096];
	size_t bn = hx(b, hex);
	if (an != bn || memcmp(a, b, an)) {
		hexdump("  got", a, an);
		hexdump("  want", b, bn);
		return 0;
	}
	return 1;
}

static void test_pb(void)
{
	uint8_t buf[256];
	struct pb_buf w;
	struct pb_rd r;
	struct pb_field f;
	static const uint64_t vs[] = { 0, 1, 127, 128, 300, 16383, 16384, 0xffffffffull, 0x8000000000000000ull, ~0ull };

	for (unsigned i = 0; i < sizeof(vs) / sizeof(vs[0]); i++) {
		pb_init(&w, buf, sizeof(buf));
		pb_varint(&w, 1 + i, vs[i]);
		pb_rd_init(&r, buf, w.n);
		CHECK(pb_next(&r, &f) == 1 && f.num == 1 + i && f.wt == PB_VARINT && f.v == vs[i]);
		CHECK(pb_next(&r, &f) == 0);
	}
	pb_init(&w, buf, sizeof(buf));
	pb_varint(&w, 1, 300);
	CHECK(w.n == 3 && buf[0] == 0x08 && buf[1] == 0xac && buf[2] == 0x02);

	pb_init(&w, buf, sizeof(buf));
	pb_sint64(&w, 4, -1);
	pb_sint64(&w, 4, 1);
	pb_sint64(&w, 4, -9223372036854775807LL - 1);
	pb_fixed32(&w, 5, 0xdeadbeef);
	pb_fixed64(&w, 6, 0x0123456789abcdefull);
	pb_float(&w, 7, -1.5f);
	pb_string(&w, 8, "accel");
	pb_bytes(&w, 2000, "", 0);
	pb_bool(&w, 9, 1);
	CHECK(!w.err);
	CHECK(buf[0] == 0x20 && buf[1] == 0x01);	/* zigzag(-1) = 1 */
	pb_rd_init(&r, buf, w.n);
	CHECK(pb_next(&r, &f) == 1 && pb_zigzag(f.v) == -1);
	CHECK(pb_next(&r, &f) == 1 && pb_zigzag(f.v) == 1);
	CHECK(pb_next(&r, &f) == 1 && pb_zigzag(f.v) == -9223372036854775807LL - 1);
	CHECK(pb_next(&r, &f) == 1 && f.num == 5 && f.wt == PB_FIXED32 && f.v == 0xdeadbeef);
	CHECK(pb_next(&r, &f) == 1 && f.num == 6 && f.wt == PB_FIXED64 && f.v == 0x0123456789abcdefull);
	CHECK(pb_next(&r, &f) == 1 && f.num == 7 && pb_f32(&f) == -1.5f);
	CHECK(pb_next(&r, &f) == 1 && f.num == 8 && f.len == 5 && !memcmp(f.data, "accel", 5));
	CHECK(pb_next(&r, &f) == 1 && f.num == 2000 && f.wt == PB_LEN && f.len == 0);
	CHECK(pb_next(&r, &f) == 1 && f.num == 9 && f.v == 1);
	CHECK(pb_next(&r, &f) == 0);

	/* packed and unpacked repeated floats */
	float fl[8];
	int n = 0;
	pb_init(&w, buf, sizeof(buf));
	pb_float(&w, 1, 1.0f);
	float pk[2] = { 2.0f, 3.0f };
	pb_bytes(&w, 1, pk, sizeof(pk));
	pb_rd_init(&r, buf, w.n);
	while (pb_next(&r, &f) == 1)
		n = pb_floats(&f, fl, n, 8);
	CHECK(n == 3 && fl[0] == 1.0f && fl[1] == 2.0f && fl[2] == 3.0f);

	/* overflow sets err; malformed input is refused */
	pb_init(&w, buf, 4);
	pb_string(&w, 1, "too long");
	CHECK(w.err);
	static const uint8_t bad1[] = { 0x0a, 0x05, 'a' };		/* length past the end */
	static const uint8_t bad2[] = { 0x08, 0x80 };			/* truncated varint */
	static const uint8_t bad3[] = { 0x0b };				/* group */
	static const uint8_t bad4[] = { 0x00, 0x01 };			/* field 0 */
	pb_rd_init(&r, bad1, sizeof(bad1));
	CHECK(pb_next(&r, &f) == -1);
	pb_rd_init(&r, bad2, sizeof(bad2));
	CHECK(pb_next(&r, &f) == -1);
	pb_rd_init(&r, bad3, sizeof(bad3));
	CHECK(pb_next(&r, &f) == -1);
	pb_rd_init(&r, bad4, sizeof(bad4));
	CHECK(pb_next(&r, &f) == -1);
}

static void test_encoders(void)
{
	uint8_t pl[64], req[1024], qmi[1100];
	size_t pn = sns_enc_suid_req(pl, sizeof(pl), "accel", 1, 1);
	CHECK(same(pl, pn, canned_pl_suid_accel));
	size_t rn = sns_enc_client_request(req, sizeof(req), &sns_suid_lookup, SNS_MSG_SUID_REQ, pl, pn,
	    SNS_DELIVERY_WAKEUP);
	size_t qn = sns_qmi_request(qmi, sizeof(qmi), 1, req, rn, 1);
	CHECK(same(qmi, qn, canned_req_suid_accel));

	struct sns_suid acc = { 0x1122334455667788ull, 0x99aabbccddeeff00ull };
	pn = sns_enc_sensor_config(pl, sizeof(pl), 50.0f);
	rn = sns_enc_client_request(req, sizeof(req), &acc, SNS_MSG_SENSOR_CONFIG, pl, pn, SNS_DELIVERY_WAKEUP);
	CHECK(same(req, rn, canned_req_cfg_accel));
	CHECK(sns_qmi_request(qmi, sizeof(qmi), 1, req, 1001, 0) == 0);	/* over SNS_CLIENT_REQ_LEN_MAX */
}

/* Decoders on canned indications, without a transport. */
struct cap {
	struct motion_sample m[32];
	int n;
};
static void capture(void *ctx, struct sensor *s, const struct motion_sample *m)
{
	struct cap *c = ctx;
	(void)s;
	if (c->n < 32)
		c->m[c->n++] = *m;
}

static void test_decoders(void)
{
	uint8_t b[1024];
	size_t n;
	struct sns_qmi q;

	n = hx(b, canned_resp_t1);
	CHECK(sns_qmi_parse(b, n, &q) == 0 && q.type == QMI_RESPONSE && q.txn == 1 && q.msg_id == 0x20 &&
	    q.result == 0 && q.has_client_id && q.client_id == 0xc0ffee);
	n = hx(b, canned_suid_accel);
	CHECK(sns_qmi_parse(b, n, &q) == 0 && q.type == QMI_INDICATION && q.msg_id == 0x21 && q.client_id == 0xc0ffee);

	struct cap c = { .n = 0 };
	struct sensor_env e = { .out = capture, .out_ctx = &c, .orient = 1 };
	struct sensor s;
	sensor_init(&s, sensor_kind_find("accel"), -1, 5, 9);
	sensor_handle(&e, &s, b, n);
	CHECK(s.have_suid == 1 && s.nsuids == 1 && s.suid.low == 0x1122334455667788ull);
	n = hx(b, canned_attr_accel);
	sensor_handle(&e, &s, b, n);
	CHECK(s.have_attrs && !strcmp(s.attrs.name, "lsm6dsr") && !strcmp(s.attrs.vendor, "STMicro") &&
	    !strcmp(s.attrs.type, "accel") && s.attrs.available == 1 && s.attrs.physical == 1 && s.attrs.hw_id == 0);
	CHECK(s.attrs.nrates == 3 && s.attrs.rates[2] == 104.0f && s.attrs.have_stream_type && s.attrs.stream_type == 0);
	CHECK(NEAR(s.attrs.range_min, -78.4532f) && NEAR(s.attrs.range_max, 78.4532f));

	sensor_init(&s, sensor_kind_find("mag"), -1, 5, 9);
	CHECK(!strcmp(s.k->alias, "compass"));
	n = hx(b, canned_suid_none);
	sensor_init(&s, sensor_kind_find("pressure"), -1, 5, 9);
	sensor_handle(&e, &s, b, n);
	CHECK(s.have_suid == -1);

	CHECK(sensor_orientation_of(0, 9.8f, 0) == 1 && sensor_orientation_of(0, -9.8f, 0) == 2);
	CHECK(sensor_orientation_of(9.8f, 0, 0) == 3 && sensor_orientation_of(-9.8f, 0, 0) == 4);
	CHECK(sensor_orientation_of(0.3f, 0.2f, 9.8f) == 0 && sensor_orientation_of(6.9f, 6.9f, 0) == 0);
	CHECK(sensor_orientation_hyst(0.3f, 0.2f, 9.8f, 0) == 5 && sensor_orientation_hyst(0.3f, 0.2f, -9.8f, 1) == 6);
	CHECK(sensor_orientation_hyst(0, 9.8f, 0, 0) == 1 && sensor_orientation_hyst(9.8f, 0, 0, 1) == 3);
	CHECK(sensor_orientation_hyst(4.0f, 5.5f, 0, 3) == 3 && sensor_orientation_hyst(3.0f, 6.5f, 0, 3) == 1);
	CHECK(sensor_orientation_hyst(0, 4.5f, 6.5f, 5) == 5 && sensor_orientation_hyst(0, 4.5f, 6.5f, 0) == 1 && sensor_orientation_hyst(0, 9.0f, 3.0f, 5) == 1);
}

/* ---- the fake DSP ---- */
static size_t resp(uint8_t *out, uint16_t txn)
{
	size_t n = hx(out, canned_resp_t1);
	memcpy(out + 1, &txn, 2);
	return n;
}

static void fake_send(int fd, const uint8_t *d, size_t n)
{
	uint8_t f[2048];
	uint32_t node = 5, port = 9;
	memcpy(f, &node, 4);
	memcpy(f + 4, &port, 4);
	memcpy(f + 8, d, n);
	if (write(fd, f, 8 + n) != (ssize_t)(8 + n))
		_exit(3);
}

static void fake_send_hex(int fd, const char *h)
{
	uint8_t b[2048];
	fake_send(fd, b, hx(b, h));
}

static void fake_dsp(int fd)
{
	uint8_t f[4096], out[256];
	for (;;) {
		ssize_t n = read(fd, f, sizeof(f));
		if (n <= 8)
			_exit(0);
		struct qmi_msg m;
		uint16_t l;
		if (qmi_parse(f + 8, (uint32_t)(n - 8), &m) || m.type != QMI_REQUEST || m.id != 0x20)
			_exit(4);
		const uint8_t *t = qmi_get(&m, 0x01, &l);
		uint16_t pl;
		if (!t || l < 2)
			_exit(5);
		memcpy(&pl, t, 2);
		/* sns_client_request_msg: msg_id (2) and the request payload (4 -> 2) */
		struct pb_rd r, rq;
		struct pb_field fl, g;
		uint32_t msg_id = 0;
		const uint8_t *payload = NULL;
		size_t plen = 0;
		pb_rd_init(&r, t + 2, pl);
		while (pb_next(&r, &fl) == 1) {
			if (fl.num == 2 && fl.wt == PB_FIXED32)
				msg_id = (uint32_t)fl.v;
			if (fl.num == 4 && fl.wt == PB_LEN) {
				pb_rd_init(&rq, fl.data, fl.len);
				while (pb_next(&rq, &g) == 1)
					if (g.num == 2 && g.wt == PB_LEN) {
						payload = g.data;
						plen = g.len;
					}
			}
		}
		fake_send(fd, out, resp(out, m.txn));
		switch (msg_id) {
		case SNS_MSG_SUID_REQ:
			if (plen >= 7 && !memcmp(payload + 2, "accel", 5))
				fake_send_hex(fd, canned_suid_accel);
			else if (plen >= 11 && !memcmp(payload + 2, "proximity", 9))
				fake_send_hex(fd, canned_suid_prox);
			else
				fake_send_hex(fd, canned_suid_none);
			break;
		case SNS_MSG_ATTR_REQ:
			fake_send_hex(fd, canned_attr_accel);
			break;
		case SNS_MSG_SENSOR_CONFIG:
			fake_send_hex(fd, canned_data_accel);
			fake_send_hex(fd, canned_data_accel_packed);
			fake_send_hex(fd, canned_err);
			break;
		case SNS_MSG_ONCHANGE_CONFIG:
			fake_send_hex(fd, canned_prox_near);
			break;
		}
	}
}

static void test_exchange(void)
{
	int sv[2];
	/* SOCK_SEQPACKET where there is one (Linux), else datagrams (macOS; frames here stay < 2 KiB) */
	if (socketpair(AF_UNIX, SOCK_SEQPACKET, 0, sv) != 0)
		CHECK(socketpair(AF_UNIX, SOCK_DGRAM, 0, sv) == 0);
	pid_t pid = fork();
	if (pid == 0) {
		close(sv[0]);
		fake_dsp(sv[1]);
	}
	close(sv[1]);
	fcntl(sv[0], F_SETFL, O_NONBLOCK);	/* as /dev/redwood-qrtr is opened */

	struct cap c = { .n = 0 };
	struct sensor_env e = { .out = capture, .out_ctx = &c, .orient = 1, .timeout_ms = 2000 };
	struct sensor s;
	sensor_init(&s, sensor_kind_find("accel"), sv[0], 5, 9);
	CHECK(sensor_lookup(&e, &s) == 0 && s.suid.high == 0x99aabbccddeeff00ull);
	CHECK(s.client_id == 0xc0ffee);
	CHECK(sensor_get_attrs(&e, &s) == 0 && s.attrs.nrates == 3);
	sensor_print_attrs(&s);
	CHECK(sensor_start(&e, &s, 50) == 0 && s.active && s.hz == 50);
	for (int i = 0; i < 20 && (c.n < 4 || !s.last_error); i++)
		sensor_poll(&e, &s, 50);
	CHECK(c.n == 4);
	CHECK(c.m[0].type == MOTION_TYPE_ACCEL && NEAR(c.m[0].v[0], 0.1f) && NEAR(c.m[0].v[1], 9.80665f) &&
	    NEAR(c.m[0].v[2], -0.2f) && c.m[0].flags == 3 && c.m[0].ts_mach == 192000000ull);
	CHECK(c.m[1].type == MOTION_TYPE_ACCEL && c.m[1].ts_mach == 192000000ull + 7680000ull);
	CHECK(c.m[2].type == MOTION_TYPE_ORIENTATION && c.m[2].v[0] == 1.0f);	/* portrait for 0.4 s */
	CHECK(c.m[3].type == MOTION_TYPE_ACCEL && NEAR(c.m[3].v[0], 9.80665f) && NEAR(c.m[3].v[2], 0.5f) &&
	    c.m[3].flags == 2);
	CHECK(s.last_error == 4 && s.count == 3);
	CHECK(sensor_stop(&e, &s) == 0 && !s.active);

	struct sensor p;
	c.n = 0;
	sensor_init(&p, sensor_kind_find("prox"), sv[0], 5, 9);
	CHECK(sensor_lookup(&e, &p) == 0 && p.suid.low == 0x0102030405060708ull);
	CHECK(sensor_start(&e, &p, 0) == 0 && p.hz == 0);
	for (int i = 0; i < 20 && c.n < 1; i++)
		sensor_poll(&e, &p, 50);
	CHECK(c.n == 1 && c.m[0].type == MOTION_TYPE_PROX && c.m[0].v[0] == 1.0f && c.m[0].v[1] == 1000.0f &&
	    c.m[0].flags == 3);

	struct sensor q;
	sensor_init(&q, sensor_kind_find("pressure"), sv[0], 5, 9);
	CHECK(sensor_lookup(&e, &q) == -1 && q.have_suid == -1);

	close(sv[0]);
	usleep(100000);
	int st = 0;
	if (waitpid(pid, &st, WNOHANG) == 0) {	/* a datagram peer sees no EOF */
		kill(pid, SIGTERM);
		waitpid(pid, &st, 0);
		CHECK(WIFSIGNALED(st));
	} else {
		CHECK(WIFEXITED(st) && WEXITSTATUS(st) == 0);
	}
}

/* sunfish sns2: per-port routing in sns_link (adspboot's hooks): each stream's queue gets only its port's DATA. */
static uint32_t rt_lport;
static int rt_step;
static int rt_send(uint32_t lport, uint32_t node, uint32_t port, const void *d, size_t n)
{
	rt_lport = lport;
	return 0;
}
static int rt_pump(void)
{
	static const uint8_t a = 'a', b = 'b', c = 'c';
	switch (rt_step++) {	/* stream 1's message first, as als/prox indications landed in accel's wait */
	case 0: return sns_link_push(SNS_LINK_PORT0 + 1, 5, 14, &b, 1) == 0;
	case 1: return sns_link_push(SNS_LINK_PORT0 + 2, 5, 14, &c, 1) == 0;
	case 2: return sns_link_push(SNS_LINK_PORT0, 5, 14, &a, 1) == 0;
	default: return 0;
	}
}

static void test_routing(void)
{
	static const struct sns_link_ops ops = { rt_send, rt_pump };
	uint8_t d[8];
	uint32_t node, port;
	sns_link_set(&ops);
	CHECK(rqrtr_send(1, 5, 14, "x", 1) == 0 && rt_lport == SNS_LINK_PORT0 + 1);
	CHECK(rqrtr_send(SNS_LINK_NPORTS, 5, 14, "x", 1) == -1);
	CHECK(sns_link_push(0x11, 5, 14, d, 1) == -1 && !sns_link_is_port(SNS_LINK_PORT0 + SNS_LINK_NPORTS));
	CHECK(rqrtr_recv(0, &node, &port, d, sizeof(d), 100) == 1 && d[0] == 'a' && node == 5 && port == 14);
	CHECK(rqrtr_recv(0, &node, &port, d, sizeof(d), 0) == 0);	/* nothing else for stream 0 */
	CHECK(rqrtr_recv(1, &node, &port, d, sizeof(d), 0) == 1 && d[0] == 'b');
	CHECK(rqrtr_recv(2, &node, &port, d, sizeof(d), 0) == 1 && d[0] == 'c');
	CHECK(rqrtr_recv(1, &node, &port, d, sizeof(d), 0) == 0);
	sns_link_set(NULL);
}

int main(void)
{
	setvbuf(stdout, NULL, _IOLBF, 0);
	test_pb();
	test_encoders();
	test_decoders();
	test_exchange();
	test_routing();
	printf("%s (%d failures)\n", failures ? "FAILED" : "all sensd host tests passed", failures);
	return failures ? 1 : 0;
}
